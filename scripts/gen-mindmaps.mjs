#!/usr/bin/env node
// Render every CPTS `Mindmap.md` as an interactive (zoom / pan / collapse)
// markmap, and embed it into the note.
//
// Source of truth stays the Markdown file. Re-run after editing any
// Mindmap.md:   npm run mindmaps   (also runs automatically in CI)
//
// For each content/**/Mindmap.md this writes a self-contained page to
//   quartz/static/mindmaps/<slug>/index.html
// which Quartz's Static emitter copies verbatim to  /static/mindmaps/<slug>/
// (static files keep their .html, unlike assets under content/). The note
// then embeds that page via an <iframe>, inserted just after the H1 between
// the markers below so re-runs are idempotent.

import { readFile, writeFile, readdir, mkdir, rm } from "node:fs/promises"
import { join, dirname, relative } from "node:path"
import { fileURLToPath } from "node:url"

const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..")
const CONTENT = join(ROOT, "content")
const STATIC_DIR = join(ROOT, "quartz", "static", "mindmaps")
const BEGIN = "<!-- mindmap:begin (generated by scripts/gen-mindmaps.mjs) -->"
const END = "<!-- mindmap:end -->"

// Pinned for reproducible builds. Bump deliberately.
const MARKMAP_AUTOLOADER = "https://cdn.jsdelivr.net/npm/markmap-autoloader@0.18.12"

async function findMindmaps(dir) {
  const out = []
  for (const entry of await readdir(dir, { withFileTypes: true })) {
    const full = join(dir, entry.name)
    if (entry.isDirectory()) out.push(...(await findMindmaps(full)))
    else if (entry.name.toLowerCase() === "mindmap.md") out.push(full)
  }
  return out
}

function stripFrontmatter(md) {
  if (md.startsWith("---")) {
    const end = md.indexOf("\n---", 3)
    if (end !== -1) return md.slice(md.indexOf("\n", end + 1) + 1)
  }
  return md
}

/** Note body with our generated block removed. */
function stripEmbedBlock(md) {
  const i = md.indexOf(BEGIN)
  if (i === -1) return md
  const j = md.indexOf(END, i)
  const after = j === -1 ? "" : md.slice(j + END.length)
  return (md.slice(0, i).trimEnd() + "\n" + after.replace(/^\n+/, "")).trimEnd()
}

/** Stable, unique, URL-safe slug from the module folder path. */
function slugFor(mdPath) {
  const rel = relative(CONTENT, dirname(mdPath)) // e.g. CPTS/07 - File Transfers
  return rel
    .split(/[\\/]/)
    .map((s) =>
      s
        .toLowerCase()
        .replace(/[^a-z0-9]+/g, "-")
        .replace(/^-+|-+$/g, ""),
    )
    .join("/")
}

function htmlPage(title, markdown) {
  const safe = markdown.replace(/<\/script/gi, "<\\/script")
  return `<!doctype html>
<html lang="en">
<head>
<meta charset="utf-8" />
<meta name="viewport" content="width=device-width, initial-scale=1" />
<title>${title} — Mindmap</title>
<style>
  :root { color-scheme: light dark; }
  html, body { margin: 0; height: 100%; }
  body { background: #faf8f8; }
  @media (prefers-color-scheme: dark) { body { background: #1e1e21; } }
  svg.markmap { width: 100%; height: 100vh; display: block; }
</style>
<script>
  window.markmap = {
    autoLoader: {
      toolbar: true,
      options: { maxWidth: 320, spacingVertical: 8, paddingX: 16 },
    },
  }
</script>
<script async src="${MARKMAP_AUTOLOADER}"></script>
</head>
<body>
  <div class="markmap">
    <script type="text/template">
${safe}
    </script>
  </div>
</body>
</html>
`
}

function embedBlock(slug) {
  const url = `/static/mindmaps/${slug}/`
  return `${BEGIN}
<iframe src="${url}" title="Interactive mindmap" loading="lazy" style="width:100%;height:80vh;border:1px solid var(--lightgray,#ccc);border-radius:8px;background:transparent"></iframe>

> [!tip]- Interactive mindmap — scroll to zoom, drag to pan, click a node to collapse
> If the frame above does not load, [open the mindmap full-screen](${url}).
${END}`
}

/** Insert the block right after the first H1, else prepend it. */
function withEmbed(body, slug) {
  const block = embedBlock(slug)
  const m = body.match(/^#\s+.*$/m)
  if (!m) return `${block}\n\n${body.trimStart()}`
  const at = m.index + m[0].length
  return `${body.slice(0, at)}\n\n${block}\n${body.slice(at)}`
}

await rm(STATIC_DIR, { recursive: true, force: true })
await mkdir(STATIC_DIR, { recursive: true })

const files = (await findMindmaps(CONTENT)).sort()
for (const mdPath of files) {
  const raw = await readFile(mdPath, "utf8")
  const body = stripEmbedBlock(raw)
  const markdown = stripFrontmatter(body).trim()
  const slug = slugFor(mdPath)

  const h1 = markdown.match(/^#\s+(.+)$/m)
  const title = h1 ? h1[1].trim() : slug

  const outDir = join(STATIC_DIR, slug)
  await mkdir(outDir, { recursive: true })
  await writeFile(join(outDir, "index.html"), htmlPage(title, markdown), "utf8")

  const newMd = withEmbed(body, slug).trimEnd() + "\n"
  if (newMd !== raw) await writeFile(mdPath, newMd, "utf8")
}
console.log(`Generated ${files.length} interactive mindmaps -> quartz/static/mindmaps/`)
